def raw_aa_result(samples, clock_health, costs, protocol):
    rows = [row for row in samples if row["role"] == "aa_raw_timer"]
    jobs = {job["id"]: job for job in protocol["raw_aa_jobs"]}
    for row in rows:
        expected = (128, "O2") if row["tier"] == "F" else (8, "O2") if row["tier"] == "M" else None
        job = jobs.get(row["task"])
        if config_key(row) != expected or row["kernel_clock"] != "CLOCK_MONOTONIC_RAW" or \
                row["source_sha256"] != protocol["target"]["sha256"] or row.get("stage") != "raw_aa" or job is None or \
                any(row[field] != job[field] for field in ("tier", "label", "pair")):
            raise ValueError("RAW A/A changes its predetermined tier or target timer identity")
    if len({row["task"] for row in rows}) != len(rows) or len({row["binary_sha256"] for row in rows if row["valid"]}) > 1:
        raise ValueError("RAW A/A must use distinct independent processes of one O2 binary")
    aa = followup_aa_table(rows, "aa_raw_timer")
    for row in aa:
        row["D_pct"] = abs(row["signed_median_difference_pct"]) if row["signed_median_difference_pct"] is not None else None
        row["P_pct"] = max(map(abs, row["paired_difference_pct"]), default=None)
    complete = len(rows) == 8 and set(jobs) == {row["task"] for row in rows} and all(row["complete"] for row in aa)
    comparisons = []
    if complete:
        indexed = {(row["tier"], row["label"], row["pair"]): row["kernel_s"] for row in rows if row["valid"]}
        for pair in (1, 2):
            for label in ("A", "B"):
                fast, medium = indexed["F", label, pair], indexed["M", label, pair]
                comparisons.append(dict(label=label, pair=pair, fast_s=fast, medium_s=medium,
                    signed_gap_pct=100 * (medium / fast - 1)))
    scale = max((row["P_pct"] for row in aa if row["P_pct"] is not None), default=None)
    coarse = bool(comparisons and scale is not None and all(row["signed_gap_pct"] > scale for row in comparisons))
    healthy = bool(clock_health and clock_health["healthy"])
    return dict(aa=aa, rank_comparisons=comparisons, complete=complete, observed_runs=len(rows),
        invalid_runs=sum(not row["valid"] for row in rows), clock_healthy=healthy, cost_complete=costs["complete"],
        coarse_ranking_supported=coarse,
        formal_method_evidence_ready=bool(protocol.get("state") == "approved" and complete and healthy and costs["complete"] and coarse),
        formal_admission=False, different_identity_risk_supported=False,
        scope="eight independent RAW A/A observations; no CI, 5pct resolution, or 2pp noninferiority claim")


def joint_diagnostic(batch, protocol, ledger_rows, ledger_bytes, initial):
    samples = samples_from_batches([batch])
    old_samples = initial["samples"]
    old_plan = load_json(initial["root"] / "results/diagnostic_v2/plan.json")
    jobs = {job["id"]: job for job in old_plan["jobs"]}
    effective, replacements = list(old_samples), []
    for task in batch["tasks"]:
        job = task["job"]
        if job["role"] != "aa_replacement":
            continue
        original = job["replacement_for"]
        prior = jobs[original["job"]]
        old_rows = [row for row in old_samples if row["task"] == prior["id"]]
        if original["batch"] != "results/diagnostic_v2" or prior["config"] != job["config"] or \
                any(row["valid"] for row in old_rows) or any(prior[key] != job[key] for key in ("block", "method", "tier", "label", "pair")):
            raise ValueError("replacement can fill only its original invalid/unstarted matching label")
        rows = [row for row in samples if row["task"] == job["id"] and row["valid"]]
        if len(rows) == 1:
            row = dict(rows[0], role="aa", task=prior["id"], actual_replacement_task=job["id"])
            identities = {(value["source_sha256"], value["binary_sha256"]) for value in old_samples if value["valid"] and config_key(value) == config_key(row)}
            if (row["source_sha256"], row["binary_sha256"]) not in identities:
                raise ValueError("replacement target/binary identity differs from the original A/A")
            effective = [value for value in effective if value["task"] != prior["id"]] + [row]
            replacements.append(dict(original_task=prior["id"], actual_task=job["id"], kernel_s=row["kernel_s"],
                original_valid_runs=0, original_failed_runs=len(old_rows)))
    partial = aa_table(old_samples, require_complete=False)
    filled = aa_table(effective, require_complete=False)
    arrangement = choose_arrangement(filled, effective)
    new_aa = followup_aa_table(samples)
    clock = followup_clock_table(batch, protocol, ledger_rows, ledger_bytes, initial)
    rank_comparisons = []
    if all(row["complete"] for row in new_aa):
        for label in ("A", "B"):
            values = {row["tier"]: row[label.lower()]["median_s"] for row in new_aa}
            rank_comparisons.append(dict(group="new_label_" + label, signed_gap_pct=100 * (values["M"] / values["F"] - 1)))
        for pair in (1, 2):
            values = {tier: statistics.median(row["kernel_s"] for row in samples if row["valid"] and
                row["role"] == "clock_followup_aa" and row["tier"] == tier and row["pair"] == pair) for tier in ("F", "M")}
            rank_comparisons.append(dict(group="new_pair_" + str(pair), signed_gap_pct=100 * (values["M"] / values["F"] - 1)))
    selected_rank = arrangement.get("ranks", {}).get(arrangement.get("arrangement"), {}).get("comparisons", [])
    rank_same_direction = bool(rank_comparisons and selected_rank) and len({row["signed_gap_pct"] > 0 for row in
        rank_comparisons + selected_rank if row["signed_gap_pct"] != 0}) == 1 and all(row["signed_gap_pct"] != 0 for row in rank_comparisons)
    rho = arrangement.get("resolution_pp")
    new_max_pair = max((abs(value) for row in new_aa for value in row["paired_difference_pct"]), default=None)
    return dict(initial_commit=INITIAL_DIAGNOSTIC_COMMIT, initial_inputs_sha256=INITIAL_INPUTS_SHA256,
        initial_derived_sha256=initial["identity"]["derived_sha256"], initial_ledger_sha256=hashlib.sha256(initial["ledger_bytes"]).hexdigest(),
        partial_aa=partial, filled_aa=filled, replacements=replacements, new_aa=new_aa, arrangement=arrangement,
        new_rank_comparisons=rank_comparisons, rank_same_direction=rank_same_direction, clocks=clock,
        new_max_abs_pair_difference_pct=new_max_pair,
        new_AA_exceeds_initial_resolution=bool(rho is not None and new_max_pair is not None and new_max_pair > rho),
        resolution_scope="finite initial selected arrangement descriptor; not a noise bound or 5pct guarantee",
        formal_method_evidence_ready=bool(clock["complete"] and clock["complete_clock_healthy"] and
            arrangement["performance_gate"] and len(replacements) == 2 and rank_same_direction),
        formal_admission=False, interrupted_original_would_finish_stably_proven=False,
        arrangement_variance_causal_effect_proven=False, effective_samples=effective)


def numeric_clock_baseline(start, end, rows, protocol):
    """The two frozen correctness adapters may supply clocks, never scores."""
    health = protocol["measurement"]["clock_health"]
    declaration = health.get("numeric_baseline_identity")
    finite_raw = declaration is None and protocol.get("schema") == 3 and \
        health.get("guard_mode") == "complete_raw_realtime_target_and_driver" and \
        health.get("numeric_binding_path") == "evidence/measurement/raw_timing/numeric_clock_baselines.json" and \
        len(protocol.get("raw_aa_jobs", [])) == 8 and len(protocol.get("numeric_validation_jobs", [])) == 2
    if not declaration and not finite_raw:
        raise ValueError("nonformal target is not a declared clock-only numerical baseline")
    if finite_raw:
        declaration = dict(path=health["numeric_binding_path"])
    path = ex.P1 / declaration["path"]
    if not finite_raw and sha256(path) != declaration["sha256"]:
        raise ValueError("numerical clock baseline declaration changed")
    binding = load_json(path)
    raw = protocol["measurement"].get("score_clock") == "CLOCK_MONOTONIC_RAW"
    prefix = "goal2-raw-n4096" if raw else "goal2-n4096"
    role = "numeric_validation_raw" if raw else "numeric_validation"
    expected_ids = {prefix + "-O0-s24": dict(s=24, opt="O0"), prefix + "-O3-s128": dict(s=128, opt="O3")}
    if binding.get("schema") != 1 or binding.get("clock_only") is not True or binding.get("formal_scores") is not False or \
            binding["framework_sha256"] != protocol["framework"]["sha256"] or len(binding["jobs"]) != 2 or \
            {job["id"]: job["config"] for job in binding["jobs"]} != expected_ids:
        raise ValueError("numerical baseline scope differs from the two approved jobs")
    job = next((item for item in binding["jobs"] if item["id"] == start["task"]), None)
    if job is None or start["role"] != role or end["role"] != role or \
            job["role"] != role or start["attempt_id"] != job["attempt_id"] or \
            end["attempt_id"] != job["attempt_id"] or start["journal"] != job["journal"] or \
            start["prior_measurement_starts"] != 0 or end["n4096_calls"] != 1 or \
            sha256(ex.P1 / job["journal"]) != job["journal_sha256"]:
        raise ValueError("numerical clock baseline does not match its unique actual attempt and journal")
    if finite_raw:
        planned = {item["id"]: item for item in protocol["numeric_validation_jobs"]}
        if {name: item["config"] for name, item in planned.items()} != expected_ids or \
                any(item["role"] != role or item["call_upper"] != 1 for item in planned.values()) or \
                planned[job["id"]]["command"] != job["command"] or \
                planned[job["id"]]["journal"] != job["journal"]:
            raise ValueError("finite numerical binding differs from its exact two frozen validation jobs")
    adapter_path = ex.P1 / binding["adapter_identity"]
    if sha256(adapter_path) != binding["adapter_identity_sha256"]:
        raise ValueError("numerical adapter identity changed")
    adapter = load_json(adapter_path)
    if adapter["measured_source_sha256"] != protocol["target"]["sha256"] or \
            sha256(validation.__file__) != adapter["validation_script_sha256"] or adapter["formal_scores"] is not False:
        raise ValueError("numerical adapter is not derived from the frozen source and validation script")
    text = validation.validation_source(4096)
    for before, after in adapter["transformations"]:
        if text.count(before) != 1:
            raise ValueError("numerical input adapter replacement does not match its source")
        text = text.replace(before, after, 1)
    source = adapter["outputs"]["4096"]
    kernel_sha = hashlib.sha256(validation.kernel(text).encode()).hexdigest()
    if hashlib.sha256(text.encode()).hexdigest() != source["source_sha256"] or \
            kernel_sha != source["kernel_sha256"] or kernel_sha != hashlib.sha256(validation.kernel(validation.SOURCE.read_text()).encode()).hexdigest():
        raise ValueError("numerical adapter changes the measured kernel or generated source")
    root, config = Path(binding["measurement_root"]), job["config"]
    command = ["taskset", "-c", "0", "/usr/bin/python3", "-B", str(root / protocol["framework"]["path"]), "run",
        "--target", str(root / source["source"]), "--compiler", "gcc", "--cflag=-Wl,--no-as-needed", "--cflag=-lm",
        "--cache-dir", str(root / (".cache/validation-raw/build" if raw else ".cache/validation-goal2/build")),
        "--s", str(config["s"]), "--opt", config["opt"],
        "--repeats", "1", "--timeout", "1200", "--compile-timeout", "60", "--output", str(root / job["journal"])]
    metadata = rows[0]["metadata"]
    if start["command"] != command or job["command"] != command or metadata != job["metadata"] or \
            metadata["target"]["source_sha256"] != source["source_sha256"] or \
            metadata["target"]["compiler"] != protocol["target"]["compiler_identity"] or \
            metadata["target"]["flags"] != protocol["target"]["common_flags"] + adapter["validation_only_flags"] or \
            metadata["blocks"] != [config["s"]] or metadata["opts"] != [config["opt"]]:
        raise ValueError("numerical baseline command, compiler, build flags, or configuration differs")
    summary = next((row for row in reversed(rows) if row["type"] == "summary"), None)
    if not summary or summary["failed_trials"] or summary["process_runs"] != 1:
        raise ValueError("numerical baseline did not complete its independent element check")
    check_trials(dict(records=rows, summary=summary))
    measurements = [row for row in rows if row["type"] == "measurement"]
    lines = [line for row in measurements for line in row["stdout"].splitlines() if line.startswith("CHECK ")]
    match = re.fullmatch(r"CHECK n=4096 count=24 max_abs=([-+0-9.eE]+) max_rel=([-+0-9.eE]+) atol=1e-12 rtol=1e-11 failures=0", job["check"])
    if lines != [job["check"]] or not match or any(not math.isfinite(float(value)) or float(value) < 0 for value in match.groups()):
        raise ValueError("numerical baseline lacks the successful 24-element CHECK footer")
    return True


def clock_history_inputs(protocol, ledger_rows, ledger_bytes):
    """Bind legacy clocks to one exact physical prefix, without importing scores."""
    binding = protocol["measurement"]["clock_health"]["clock_history"]
    path = ex.P1 / binding["path"]
    if sha256(path) != binding["sha256"]:
        raise ValueError("clock-only history declaration changed")
    history = load_json(path)
    prefix = history["ledger_prefix"]
    count = prefix["rows"]
    if history.get("schema") != 1 or history.get("use") != "clock_baselines_only" or \
            history.get("fixed_commit") != "a39f348e6cf0c7466900ec739a797753f4d93f0b" or \
            history.get("ratio") != "raw/realtime" or type(count) is not int or count < 0 or \
            len(ledger_rows) < count or ex.at.fingerprint(ledger_rows[:count]) != prefix["fingerprint"]:
        raise ValueError("clock history differs from its exact committed ledger prefix")
    if ledger_bytes is None:
        raise ValueError("RAW clock history requires the same original ledger bytes snapshot")
    raw_prefix = b"".join(ledger_bytes.splitlines(keepends=True)[:count])
    if len(raw_prefix) != prefix["bytes"] or hashlib.sha256(raw_prefix).hexdigest() != prefix["sha256"]:
        raise ValueError("clock history original ledger prefix bytes changed")
    entries = history["legacy_journals"]
    if len({entry["path"] for entry in entries}) != len(entries):
        raise ValueError("duplicate legacy clock-only journal")
    for declaration in [history["legacy_numeric_binding"], *history["legacy_diagnostic_identity_files"], *entries]:
        raw = ex.P1 / declaration["path"]
        if sha256(raw) != declaration["sha256"]:
            raise ValueError("fixed legacy clock input changed: " + declaration["path"])
        if "metadata_fingerprint" in declaration:
            header = read_records(raw)[0]
            if header.get("fingerprint") != declaration["metadata_fingerprint"] or \
                    ex.at.fingerprint(header["metadata"]) != declaration["metadata_fingerprint"]:
                raise ValueError("fixed legacy clock journal header changed")
    formal = dict(framework_sha256=protocol["framework"]["sha256"], source_sha256=protocol["target"]["sha256"],
        n=4096, kernel_clock="CLOCK_MONOTONIC_RAW", compiler=protocol["target"]["compiler_identity"],
        flags=protocol["target"]["common_flags"], runtime_affinity=protocol["measurement"]["cpu_affinity"])
    identities = history["new_target_identities"]
    if len(identities) != 2 or formal not in identities or any(identity["framework_sha256"] != formal["framework_sha256"] or
            identity["n"] != 4096 or identity["kernel_clock"] != formal["kernel_clock"] or
            identity["compiler"] != formal["compiler"] or identity["runtime_affinity"] != formal["runtime_affinity"] or
            identity["flags"] not in (formal["flags"], formal["flags"] + ["-Wl,--no-as-needed", "-lm"])
            for identity in identities):
        raise ValueError("RAW clock history changes the allowed computation/build identities")
    return history


def clock_baseline_header(start, end, rows, protocol, history, legacy=False, owned=False):
    metadata = rows[0]["metadata"]
    target = metadata["target"]
    if rows[0].get("fingerprint") != ex.at.fingerprint(metadata):
        raise ValueError("clock baseline header lacks its original fingerprint")
    if legacy:
        entries = [entry for entry in history["legacy_journals"] if entry["path"] == start["journal"]]
        old = history["legacy_target"]
        if owned or len(entries) != 1 or entries[0]["metadata_fingerprint"] != rows[0]["fingerprint"] or \
                read_records(ex.P1 / start["journal"]) != rows or \
                metadata.get("framework_sha256") != old["framework_sha256"] or \
                metadata.get("runtime_affinity") != protocol["measurement"]["cpu_affinity"] or \
                target["n"] != old["n"] or target["kernel_clock"] != old["kernel_clock"] or \
                target["compiler"] != old["compiler_identity"]:
            raise ValueError("legacy clock baseline is outside its frozen source/build scope")
        if target["source_sha256"] == old["sha256"] and target["flags"] == old["common_flags"]:
            return True
        binding = load_json(ex.P1 / history["legacy_numeric_binding"]["path"])
        job = next((item for item in binding["jobs"] if item["journal"] == start["journal"]), None)
        if binding.get("clock_only") is not True or binding.get("formal_scores") is not False or \
                len(binding["jobs"]) != 2 or job is None or metadata != job["metadata"] or \
                start["command"] != job["command"] or start["task"] != job["id"] or \
                start["role"] != "numeric_validation" or end["role"] != "numeric_validation" or \
                start["attempt_id"] != job["attempt_id"] or end["attempt_id"] != job["attempt_id"] or \
                start["prior_measurement_starts"] != 0 or end["n4096_calls"] != 1:
            raise ValueError("legacy numerical clock baseline differs from its two actual bound processes")
        return True
    identity = dict(framework_sha256=metadata.get("framework_sha256"), source_sha256=target.get("source_sha256"),
        n=target.get("n"), kernel_clock=target.get("kernel_clock"), compiler=target.get("compiler"),
        flags=target.get("flags"), runtime_affinity=metadata.get("runtime_affinity"))
    if identity not in history["new_target_identities"]:
        raise ValueError("new clock baseline source/build identity is not frozen")
    if target["source_sha256"] != protocol["target"]["sha256"] or target["flags"] != protocol["target"]["common_flags"]:
        if owned:
            raise ValueError("numerical adapters cannot supply formal score samples")
        numeric_clock_baseline(start, end, rows, protocol)
    return True


def formal_clock_health(batches, ledger_rows, protocol, ledger_bytes=None):
    """Verify whole target/driver checks by actual attempt, before scoring samples."""
    active = {}
    for batch in batches:
        for task in batch["tasks"]:
            path = batch["path"] / (task["job"]["id"] + ".jsonl")
            journal = str(path.resolve().relative_to(ex.P1.resolve()))
            if journal in active:
                raise ValueError("duplicate formal journal cannot be counted as a new clock observation")
            active[journal] = task["records"]
    result = dict(healthy=False, attempts=[], missing_jobs=[], states={})
    mode = protocol["measurement"]["clock_health"].get("guard_mode")
    raw = mode == "complete_raw_realtime_target_and_driver"
    if ledger_rows is None or mode not in ("complete_target_and_driver", "complete_raw_realtime_target_and_driver"):
        result["missing_jobs"] = sorted(active)
        result["states"] = dict.fromkeys(active, "clock_unverified")
        return result
    migration = clock_history_inputs(protocol, ledger_rows, ledger_bytes) if raw else None
    legacy_ends = {row["attempt_id"] for row in ledger_rows[:migration["ledger_prefix"]["rows"]]
                   if row["type"] == "task_end"} if raw else set()
    denominator = "realtime" if raw else "monotonic"
    starts, ended, histories, covered, process_coverage = {}, set(), {}, set(), {}
    priority = dict(complete=0, clock_unverified=1, clock_conflict=2)
    for end in ledger_rows:
        if end["type"] == "task_start":
            if end["attempt_id"] in starts:
                raise ValueError("duplicate formal global attempt start")
            starts[end["attempt_id"]] = end
            continue
        if end["type"] != "task_end":
            continue
        if end["attempt_id"] not in starts or end["attempt_id"] in ended:
            raise ValueError("formal clock completion has no unique earlier attempt start")
        ended.add(end["attempt_id"])
        start = starts[end["attempt_id"]]
        if end["task"] != start["task"]:
            raise ValueError("formal completion changed its actual task identity")
        journal, owned = start.get("journal"), start.get("journal") in active
        history = histories.setdefault(start["boot_id"], dict(driver=[], process=[]))
        usable = end.get("returncode") == 0 and end.get("reason") is None and \
            end.get("n4096_calls_known", True) and end.get("n4096_calls", 0) > 0 and not end.get("clock_conflict")
        if not owned and not usable:
            continue
        if owned and end.get("n4096_calls_known") is not True:
            covered.add(journal)
            prior = result["states"].get(journal, "complete")
            result["states"][journal] = max((prior, "clock_unverified"), key=priority.get)
            result["attempts"].append(dict(attempt_id=end["attempt_id"], journal=journal, healthy=False,
                                           reason="actual completed clock/call coverage is unknown"))
            continue
        spans = clock_spans(start["clock_start_ns"], end["clock_end_ns"])
        if any(not finite_positive(value) for value in spans.values()) or \
                spans != end.get("clock_elapsed_s") or spans["monotonic"] != end.get("driver_wall_s") or \
                max(spans.values()) != end.get("resource_wall_s") or max(spans.values()) != end.get("resource_s"):
            raise ValueError("formal clock resource costs differ from the original multi-domain boundaries")
        rows = active[journal] if owned else read_records(ex.P1 / journal) if journal else []
        actual = []
        if journal and rows:
            metadata = rows[0]["metadata"]
            if raw:
                clock_baseline_header(start, end, rows, protocol, migration,
                    legacy=end["attempt_id"] in legacy_ends, owned=owned)
            elif rows[0].get("fingerprint") != ex.at.fingerprint(metadata) or \
                    metadata["target"]["n"] != 4096 or metadata["target"]["kernel_clock"] != "CLOCK_MONOTONIC" or \
                    metadata["target"]["compiler"] != protocol["target"]["compiler_identity"] or \
                    metadata.get("framework_sha256") != protocol["framework"]["sha256"] or \
                    metadata.get("runtime_affinity") != protocol["measurement"]["cpu_affinity"]:
                raise ValueError("clock baseline target/header identity differs from the frozen computation")
            if not raw and (metadata["target"]["source_sha256"] != protocol["target"]["sha256"] or \
                    metadata["target"]["flags"] != protocol["target"]["common_flags"]):
                if owned:
                    raise ValueError("formal score target cannot use numerical validation adapters")
                numeric_clock_baseline(start, end, rows, protocol)
            keys = [(row["run_id"], row["trial_id"], row["repeat"], row["pid"]) for row in rows if row["type"] == "measurement_start"]
            offset, count = start["prior_measurement_starts"], end["n4096_calls"]
            if len(set(keys)) != len(keys) or type(offset) is not int or offset < 0 or type(count) is not int or count < 0 or \
                    count > start["call_upper"]:
                raise ValueError("formal physical process starts or attempt allocation are invalid")
            selected = set(keys[offset:offset + count])
            if len(selected) != count:
                raise ValueError("clock checks do not match actual attempt process starts")
            actual = [row for row in rows if row["type"] == "measurement" and
                (row["run_id"], row["trial_id"], row["repeat"], row["pid"]) in selected]
            if len({(row["run_id"], row["trial_id"], row["repeat"], row["pid"]) for row in actual}) != len(actual):
                raise ValueError("formal attempt has duplicate target process completions")
            if owned:
                previous = process_coverage.setdefault(journal, set())
                if previous & selected:
                    raise ValueError("formal attempts reuse the same physical target process starts")
                previous.update(selected)
        if not owned and (not raw or end["attempt_id"] in legacy_ends):
            # These fields establish clock history only; old scores still require
            # their pinned analysis version rather than this driver's dispatcher.
            if journal and len(actual) != end["n4096_calls"]:
                raise ValueError("prior successful attempt lacks complete target process observations")
            for row in actual:
                target = clock_spans(row["clock_start_ns"], row["clock_end_ns"], target_process=True)
                raw_deltas = dict(zip(("CLOCK_MONOTONIC", "CLOCK_MONOTONIC_RAW", "CLOCK_REALTIME"), target.values()))
                if row["status"] != "ok" or row["returncode"] != 0 or row.get("clock_unit") != "ns" or \
                        row.get("clock_read_order") != ["CLOCK_MONOTONIC", "CLOCK_MONOTONIC_RAW", "CLOCK_REALTIME"] or \
                        row.get("process_wall_clock") != "CLOCK_MONOTONIC" or row["clock_deltas_s"] != raw_deltas or \
                        row["process_wall_s"] != target["monotonic"] or \
                        any(not finite_positive(value) for value in target.values()):
                    raise ValueError("successful prior target has invalid complete clock fields")
                if target["monotonic"] >= 10:
                    history["process"].append(dict(identity=[row["run_id"], row["trial_id"], row["repeat"], row["pid"]],
                        attempt_id=end["attempt_id"], q=target["raw"] / target[denominator]))
            if spans["monotonic"] >= 10:
                history["driver"].append(dict(identity=end["attempt_id"], q=spans["raw"] / spans[denominator]))
            continue
        if owned:
            covered.add(journal)
        guard = end.get("clock_guard")
        guard_keys = {"schema", "mode", "threshold_fraction", "boot_id", "process_checks", "driver_check", "complete", "error"}
        if raw:
            guard_keys.add("history")
        if not isinstance(guard, dict) or type(end.get("clock_conflict")) is not bool or \
                set(guard) != guard_keys or \
                type(guard.get("schema")) is not int or guard["schema"] != (2 if raw else 1) or guard.get("mode") != mode or \
                (raw and guard.get("history") != protocol["measurement"]["clock_health"]["clock_history"]) or \
                guard.get("threshold_fraction") != .02 or guard.get("boot_id") != start["boot_id"]:
            prior = result["states"].get(journal, "complete")
            result["states"][journal] = max((prior, "clock_unverified"), key=priority.get)
            result["attempts"].append(dict(attempt_id=end["attempt_id"], journal=journal, healthy=False,
                                           reason="missing mandatory completed-clock identity"))
            continue
        local_history, checks = list(history["process"]), []
        all_valid = len(actual) == end["n4096_calls"] and bool(actual)
        for row in actual:
            if row.get("status") != "ok" or row.get("returncode") != 0 or row.get("clock_unit") != "ns":
                all_valid = False
                continue
            target = clock_spans(row["clock_start_ns"], row["clock_end_ns"], target_process=True)
            expected_deltas = dict(zip(("CLOCK_MONOTONIC", "CLOCK_MONOTONIC_RAW", "CLOCK_REALTIME"), target.values()))
            if row.get("clock_read_order") != list(expected_deltas) or row.get("process_wall_clock") != "CLOCK_MONOTONIC" or \
                    row["clock_deltas_s"] != expected_deltas or \
                    row["process_wall_s"] != target["monotonic"] or any(not finite_positive(value) for value in target.values()):
                raise ValueError("formal target clock observations differ from their original nanoseconds")
            q = target["raw"] / target[denominator]
            baselines = local_history[:1] + local_history[-1:]
            identity = [row["run_id"], row["trial_id"], row["repeat"], row["pid"]]
            check = dict(source="target_process", identity=identity, clock_elapsed_s=target, q=q,
                         baselines=baselines, conflict=any(abs(q / ref["q"] - 1) > .02 for ref in baselines))
            checks.append(check)
            if not check["conflict"] and target["monotonic"] >= 10:
                local_history.append(dict(identity=identity, attempt_id=end["attempt_id"], q=q))
        driver_q = spans["raw"] / spans[denominator] if finite_positive(spans[denominator]) else None
        refs = history["driver"][:1] + history["driver"][-1:]
        driver = dict(source="driver", identity=end["attempt_id"], clock_elapsed_s=spans, q=driver_q,
            baselines=refs, conflict=any(abs(driver_q / ref["q"] - 1) > .02 for ref in refs)) if driver_q else None
        saved_checks = guard.get("process_checks")
        if not isinstance(saved_checks, list) or len(saved_checks) > len(checks) or \
                ex.at.fingerprint(saved_checks) != ex.at.fingerprint(checks[:len(saved_checks)]) or \
                (guard.get("driver_check") is not None and ex.at.fingerprint(guard["driver_check"]) != ex.at.fingerprint(driver)):
            raise ValueError("formal completed-clock checks differ from raw sources and first/previous identities")
        conflict = any(check["conflict"] for check in saved_checks) or bool(guard.get("driver_check") and driver and driver["conflict"])
        if end["clock_conflict"] != conflict or type(guard.get("complete")) is not bool or \
                guard["complete"] != (len(saved_checks) == end["n4096_calls"]) or \
                (guard.get("error") is not None and not isinstance(guard["error"], str)):
            raise ValueError("formal completed-clock coverage or flags differ from actual processes")
        healthy = bool(usable and all_valid and guard["complete"] and guard.get("driver_check") is not None and
                       not conflict and guard.get("error") is None and
                       (not raw or bool(history["process"] and history["driver"])))
        result["attempts"].append(dict(attempt_id=end["attempt_id"], journal=journal, healthy=healthy,
                                       conflict=conflict, complete=guard["complete"]))
        state = "complete" if healthy else "clock_conflict" if conflict else "clock_unverified"
        prior_state = result["states"].get(journal, "complete")
        result["states"][journal] = max((state, prior_state), key=priority.get)
        if healthy:
            history["process"] = local_history
            if spans["monotonic"] >= 10:
                history["driver"].append(dict(identity=end["attempt_id"], q=driver_q))
    result["missing_jobs"] = sorted(set(active) - covered)
    for identity, start in starts.items():
        if identity not in ended and start.get("journal") in active:
            journal = start["journal"]
            result["states"][journal] = max((result["states"].get(journal, "complete"), "clock_unverified"), key=priority.get)
            result["attempts"].append(dict(attempt_id=identity, journal=journal, healthy=False,
                                           reason="formal attempt has no completed clock observation"))
    for journal, rows in active.items():
        actual_count = sum(row["type"] == "measurement_start" for row in rows)
        if len(process_coverage.get(journal, set())) != actual_count:
            result["states"][journal] = max((result["states"].get(journal, "complete"), "clock_unverified"), key=priority.get)
            result["attempts"].append(dict(journal=journal, healthy=False,
                                           reason="formal attempts do not cover every physical process start"))
    for journal in result["missing_jobs"]:
        result["states"][journal] = "clock_unverified"
    result["healthy"] = not result["missing_jobs"] and bool(result["attempts"]) and all(row["healthy"] for row in result["attempts"])
    return result


def paired_rows(runs, grid, panels, protocol, stage):
    reference = min(grid, key=lambda row: row["median_s"])
    indexed = {config_key(row): row for row in grid}
    panel_index = {(row["stage"], row["block"], config_key(row)): row for row in panels}
    run_index = {}
    for row in runs:
        if row["stage"] != stage:
            continue
        identity = row["stage"], row["algorithm"], row["seed"]
        if identity in run_index:
            raise ValueError("duplicate real search identity cannot overwrite a prior batch")
        run_index[identity] = row
    seeds = protocol["online"]["seeds"] if stage == "comparison" else protocol["holdout"]["seeds"]
    pairs = []
    for seed in seeds:
        a, b = run_index.get((stage, "random", seed)), run_index.get((stage, "recheck", seed))
        if a is None or b is None:
            continue
        ca, cb = (a["returned_s"], a["returned_opt"]), (b["returned_s"], b["returned_opt"])
        pa, pb = panel_index.get((stage, a["block"], ca)), panel_index.get((stage, b["block"], cb))
        pref = panel_index.get((stage, a["block"], config_key(reference)))
        same = ca == cb and ca in indexed
        ref_bounds = gain_bounds(indexed.get(ca, {}), indexed.get(cb, {}), reference, same)
        panel_bounds = gain_bounds(pa or {}, pb or {}, pref or {}, same)
        wall_a, wall_b = a["search_driver_wall_s"], b["search_driver_wall_s"]
        raw_a, raw_b = a.get("search_driver_raw_s"), b.get("search_driver_raw_s")
        clock = protocol["measurement"].get("cost_clock", "CLOCK_MONOTONIC")
        if clock not in ("CLOCK_MONOTONIC", "CLOCK_MONOTONIC_RAW"):
            raise ValueError("search comparison requires an explicitly supported driver cost clock")
        cost_a, cost_b = (raw_a, raw_b) if clock == "CLOCK_MONOTONIC_RAW" else (wall_a, wall_b)
        valid = a["state"] == b["state"] == "complete" and pa is not None and pb is not None and \
            pref is not None and pa["complete"] and pb["complete"] and pref["complete"]
        pairs.append(dict(stage=stage, seed=seed, block=a["block"], valid=valid, same_config=same,
            baseline_config=dict(s=ca[0], opt=ca[1]), candidate_config=dict(s=cb[0], opt=cb[1]),
            gain_ref_pp=a["gap_ref_pct"] - b["gap_ref_pct"] if ca in indexed and cb in indexed else None,
            gain_ref_low_pp=ref_bounds[0], gain_ref_high_pp=ref_bounds[1],
            gain_panel_pp=100 * (pa["median_s"] - pb["median_s"]) / pref["median_s"] if valid else None,
            gain_panel_low_pp=panel_bounds[0], gain_panel_high_pp=panel_bounds[1],
            reference_panel_conflict=ranges_conflict(ref_bounds, panel_bounds,
                protocol["measurement"]["clock_health"]["resolution_pp"]),
            baseline_calls=a["process_runs"], candidate_calls=b["process_runs"],
            baseline_wall_s=wall_a, candidate_wall_s=wall_b,
            baseline_raw_s=raw_a, candidate_raw_s=raw_b, cost_clock=clock,
            baseline_cost_s=cost_a, candidate_cost_s=cost_b,
            cost_saving_fraction=1 - cost_b / cost_a if finite_positive(cost_a) and finite_positive(cost_b) else None,
            wall_saving_fraction=1 - wall_b / wall_a if finite_positive(wall_a) and finite_positive(wall_b) else None))
    return pairs


def pair_cost_saving(row, protocol):
    clock = protocol["measurement"].get("cost_clock", "CLOCK_MONOTONIC")
    if clock == "CLOCK_MONOTONIC_RAW":
        return row.get("cost_saving_fraction") if row.get("cost_clock") == clock else None
    if clock != "CLOCK_MONOTONIC":
        return None
    return row.get("cost_saving_fraction", row.get("wall_saving_fraction"))


def decision(pairs, protocol, expected_count, project_cost_complete=True, project_clock_healthy=True):
    rules = protocol["acceptance"]
    rho = protocol["measurement"]["clock_health"]["resolution_pp"]
    if protocol.get("state") != "approved" or rules.get("state") != "frozen" or not finite_positive(rho):
        return dict(decision="INCONCLUSIVE", reasons=["formal protocol and diagnostic resolution are not frozen"])
    if not project_cost_complete:
        return dict(decision="INCONCLUSIVE", reasons=["global actual cost ledger is missing, unfinished, or contains recovered unknown cost"])
    if not project_clock_healthy:
        return dict(decision="INCONCLUSIVE", reasons=["complete measurement clock conflicts remain in the compared batches"])
    if len(pairs) != expected_count or any(not row["valid"] or row["gain_ref_pp"] is None or
            pair_cost_saving(row, protocol) is None or None in (row["gain_ref_low_pp"], row["gain_ref_high_pp"],
            row["gain_panel_low_pp"], row["gain_panel_high_pp"]) for row in pairs):
        return dict(decision="INCONCLUSIVE", reasons=["missing valid paired searches/panels or known actual cost"])
    if rules.get("different_identity_risk_supported") is not True and any(not row["same_config"] for row in pairs):
        return dict(decision="INCONCLUSIVE", reasons=["diagnostic evidence does not support the 2pp risk limit for different configuration identities"])
    if any(row["baseline_calls"] != protocol["online"]["budget"] or
            row["candidate_calls"] != protocol["online"]["budget"] for row in pairs):
        return dict(decision="INCONCLUSIVE", reasons=["incomplete equal-call-budget comparison"])
    if any(row.get("reference_panel_conflict") for row in pairs):
        return dict(decision="INCONCLUSIVE", reasons=["reference and simultaneous panel conflict beyond diagnostic resolution"])
    loss = rules["quality_loss_pp"]
    lows = [min(row["gain_ref_low_pp"], row["gain_panel_low_pp"]) - (0 if row["same_config"] else rho) for row in pairs]
    highs = [max(row["gain_ref_high_pp"], row["gain_panel_high_pp"]) + (0 if row["same_config"] else rho) for row in pairs]
    clear_loss = any(not at_least(value, -loss) for value in highs)
    severe = any(not at_least(value, -rules["severe_regression_pp"]) for value in highs)
    if clear_loss or severe:
        return dict(decision="REJECT", reasons=["observed quality risk exceeds the frozen limit"], severe_regression=severe)
    risk_safe = all(at_least(value, -loss) for value in lows)
    gains = [row["gain_ref_pp"] for row in pairs]
    saving = statistics.median(pair_cost_saving(row, protocol) for row in pairs)
    useful_quality = at_least(statistics.median(lows), rules["quality_gain_median_pp"]) and \
        sum(at_least(value, rules["quality_gain_seed_pp"]) for value in lows) >= rules["minimum_improving_seeds"]
    quality_supported = at_least(statistics.median(lows), rules["quality_gain_median_pp"])
    quality_cost = at_least(saving, -rules["quality_cost_increase_fraction"])
    efficiency = at_least(saving, rules["efficiency_wall_saving_fraction"])
    conditions = dict(risk_safe=risk_safe, useful_quality=useful_quality, quality_supported=quality_supported,
                      quality_cost=quality_cost, efficiency=efficiency)
    if not risk_safe:
        status, reasons = "INCONCLUSIVE", ["descriptive ranges cross the 2pp risk limit; they are not confidence intervals"]
    elif efficiency:
        status, reasons = "KEEP", ["quality-safe measured time saving route passed"]
    elif useful_quality and quality_supported and quality_cost:
        status, reasons = "KEEP", ["quality route passed for these measured blocks"]
    else:
        status, reasons = "REJECT", ["no useful gain under the frozen quality/cost decision table"]
    return dict(decision=status, reasons=reasons, conditions=conditions,
                median_gain_ref_pp=statistics.median(gains),
                cost_clock=protocol["measurement"].get("cost_clock", "CLOCK_MONOTONIC"),
                median_cost_saving_fraction=saving,
                median_wall_saving_fraction=statistics.median(row["wall_saving_fraction"] for row in pairs))


def final_retention(selection, confirmation):
    return dict(selection=selection["decision"], confirmation=confirmation["decision"],
                retained=selection["decision"] == confirmation["decision"] == "KEEP",
                default_algorithm="recheck" if selection["decision"] == confirmation["decision"] == "KEEP" else "random")


def search_stage_decisions(batches, stage_pairs, protocol, reference_complete,
                           project_cost_complete, project_clock_healthy):
    """Unstarted dependent experiments are not completed negative selections."""
    common = []
    if not reference_complete:
        common.append("the complete 20-configuration reference table is unavailable")
    if not project_cost_complete:
        common.append("the actual project cost ledger is incomplete")
    if not project_clock_healthy:
        common.append("the compared measurements have unresolved clock conflicts or missing clock evidence")
    if protocol.get("state") != "approved" or protocol["acceptance"].get("state") != "frozen" or \
            not finite_positive(protocol["measurement"]["clock_health"]["resolution_pp"]):
        common.append("the formal decision rules and diagnostic resolution are not frozen")
    outcomes = {}
    for stage, count in (("comparison", len(protocol["online"]["seeds"])),
                         ("confirmation", len(protocol["holdout"]["seeds"]))):
        started = [task["job"]["id"] for batch in batches if batch["manifest"]["stage"] == stage
            for task in batch["tasks"] if task["job"]["action"] == "search" and
            (stage != "confirmation" or task["job"].get("algorithm") == "recheck") and any(
                row["type"] in ("session_start", "trial_start", "build_start", "measurement_start", "summary")
                for row in task["records"])]
        pairs = stage_pairs[stage]
        dependencies = list(common)
        if len(pairs) != count or any(not row["valid"] or None in (
                row["gain_ref_pp"], pair_cost_saving(row, protocol), row["gain_ref_low_pp"],
                row["gain_ref_high_pp"], row["gain_panel_low_pp"], row["gain_panel_high_pp"]) for row in pairs):
            dependencies.append("the required valid paired searches and common confirmation panels are incomplete")
        if any(row["baseline_calls"] != protocol["online"]["budget"] or
               row["candidate_calls"] != protocol["online"]["budget"] for row in pairs):
            dependencies.append("the equal actual-call-budget comparison is incomplete")
        if any(row.get("reference_panel_conflict") for row in pairs):
            dependencies.append("the reference table and simultaneous panel remain in conflict")
        result = decision(pairs, protocol, count, project_cost_complete, project_clock_healthy)
        result.update(executed=bool(started), observed_search_tasks=started,
                      evaluation_complete=bool(started) and not dependencies, dependencies=dependencies)
        if not started:
            result.update(decision="NOT_EXECUTED", reasons=[f"no actual search is recorded for {stage}"])
        outcomes[stage] = result
    selection, confirmation = outcomes["comparison"], outcomes["confirmation"]
    if not confirmation["executed"]:
        if selection["evaluation_complete"] and selection["decision"] != "KEEP":
            confirmation.update(decision="NOT_REQUIRED", dependencies=[],
                reasons=["the completed valid main selection did not select S3; baseline confirmation is still required"])
        elif selection["evaluation_complete"] and selection["decision"] == "KEEP":
            confirmation["dependencies"].append("the selected candidate requires new-seed paired confirmation")
            confirmation["reasons"] = ["selected S3 confirmation has not executed on the new seeds"]
        else:
            confirmation["dependencies"].append("a completed main selection must precede candidate confirmation")
            confirmation["reasons"] = ["S3 confirmation has not executed; the main selection or its new-seed confirmation remains pending"]
    return outcomes


def baseline_confirmation(runs, seeds):
    rows = [row for row in runs if row["stage"] == "confirmation" and row["algorithm"] == "random"]
    return dict(expected_seeds=seeds, observed_seeds=[row["seed"] for row in rows],
        complete=sorted(row["seed"] for row in rows if row["state"] == "complete" and
            row["confirmation_complete"]) == sorted(seeds), quality_classes=[row["quality_class"] for row in rows])


def cost_table(batches, ledger_rows=None):
    """Count every actual driver attempt once; common panels have no per-algorithm copies."""
    attempts, context = {}, {}
    for batch in batches:
        roles = {task["job"]["id"]: task["job"]["role"] for task in batch["tasks"]}
        for row in batch["driver"]:
            if row["type"] != "task_end":
                continue
            identity = row["attempt_id"]
            if identity in attempts:
                raise ValueError("shared actual attempt would be counted twice")
            attempts[identity] = row
            context[identity] = batch["manifest"]["stage"], roles.get(row["task"], row["role"])
    unfinished, missing_jobs, starts, ends = [], [], {}, {}
    if ledger_rows is not None:
        starts, ends = {}, {}
        for row in ledger_rows:
            if row["type"] == "task_start":
                if row["attempt_id"] in starts:
                    raise ValueError("duplicate global ledger attempt")
                starts[row["attempt_id"]] = row
            elif row["type"] == "task_end":
                identity = row["attempt_id"]
                if identity not in starts or identity in ends or row["task"] != starts[identity]["task"]:
                    raise ValueError("global ledger completion has no matching unique start")
                ends[identity] = row
        for identity, row in attempts.items():
            actual = {key: value for key, value in row.items() if key not in ("type", "at")}
            recorded = {key: value for key, value in ends.get(identity, {}).items() if key not in ("type", "at")}
            if identity not in ends or actual != recorded:
                raise ValueError("batch cost differs from the same actual global ledger attempt")
        attempts = ends
        unfinished = [identity for identity in starts if identity not in ends]
        for batch in batches:
            for task in batch["tasks"]:
                task_rows = [row for row in batch["driver"] if row["type"] == "task_end" and row["task"] == task["job"]["id"]]
                recorded_starts = sum(row["type"] == "measurement_start" for row in task["records"])
                if recorded_starts and batch.get("path") is not None:
                    # A guarded task can finish in the global ledger before the
                    # batch driver appends its copy. Match the actual journal,
                    # not just the reusable task label, without writing raw.
                    journal = Path(batch["path"]).resolve() / (task["job"]["id"] + ".jsonl")
                    try:
                        expected_journal = str(journal.relative_to(ex.P1.resolve()))
                    except ValueError:
                        expected_journal = None
                    if expected_journal is not None:
                        matched = [row for identity, row in ends.items() if row["task"] == task["job"]["id"] and
                                   starts[identity].get("journal") == expected_journal]
                        if any(row["attempt_id"] not in {end["attempt_id"] for end in matched} for row in task_rows):
                            raise ValueError("batch cost task does not match its actual global journal")
                        task_rows = matched
                        for row in task_rows:
                            context[row["attempt_id"]] = batch["manifest"]["stage"], task["job"]["role"]
                if not task_rows:
                    if recorded_starts:
                        missing_jobs.append(dict(stage=batch["manifest"]["stage"], task=task["job"]["id"],
                                                 recorded_process_starts=recorded_starts))
                    continue
                if any(not row.get("n4096_calls_known", True) for row in task_rows):
                    continue
                if sum(row["n4096_calls"] for row in task_rows) != recorded_starts:
                    raise ValueError("actual task attempts do not match the target journal process starts")
    grouped = {}
    for identity, row in attempts.items():
        stage, role = context.get(identity, ("goal", row["role"]))
        target = grouped.setdefault((stage, role), dict(stage=stage, role=role, process_runs=0,
            process_runs_known=True, recorded_process_lower=0,
            full_driver_wall_s=0.0, conservative_resource_s=0.0, failed_tasks=0, tasks=0,
            domains_s=dict(monotonic=0.0, raw=0.0, realtime=0.0), unknown_attempts=[]))
        if type(row["n4096_calls"]) is not int or row["n4096_calls"] < 0:
            raise ValueError("invalid actual target process count")
        target["process_runs"] += row["n4096_calls"]
        known = row.get("n4096_calls_known", True) and row.get("driver_wall_s") is not None and \
            row.get("clock_elapsed_s") is not None and row.get("resource_bound_basis") is None
        if ledger_rows is not None and known:
            start, end = starts[identity]["clock_start_ns"], row["clock_end_ns"]
            if set(start) != {"monotonic", "raw", "realtime"} or start.keys() != end.keys() or \
                    any(type(value) is not int for value in [*start.values(), *end.values()]):
                raise ValueError("invalid global cost boundary domains or nanoseconds")
            spans = {name: (end[name] - value) / 1e9 for name, value in start.items()}
            if any(not math.isfinite(value) or value < 0 for value in spans.values()) or \
                    spans != row["clock_elapsed_s"] or spans["monotonic"] != row["driver_wall_s"] or \
                    max(spans.values()) != row["resource_wall_s"] or \
                    row.get("resource_s", row["resource_wall_s"]) != max(spans.values()):
                raise ValueError("actual task costs differ from the original multi-domain boundaries")
            if row["n4096_calls"] > starts[identity]["call_upper"]:
                raise ValueError("actual task calls exceed the reserved target-call upper bound")
        target["process_runs_known"] = target["process_runs_known"] and row.get("n4096_calls_known", True)
        target["recorded_process_lower"] += row.get("n4096_call_recorded_lower", row["n4096_calls"])
        if not known:
            target["unknown_attempts"].append(identity)
        for name, field in (("full_driver_wall_s", "driver_wall_s"), ("conservative_resource_s", "resource_wall_s")):
            value = row.get(field)
            if value is None:
                target[name] = None
            elif not math.isfinite(value) or value < 0:
                raise ValueError("invalid actual driver/resource cost")
            elif target[name] is not None:
                target[name] += value
        if row.get("clock_elapsed_s") is None:
            target["domains_s"] = dict.fromkeys(target["domains_s"], None)
        for domain, value in (row.get("clock_elapsed_s") or {}).items():
            if domain not in target["domains_s"] or not math.isfinite(value) or value < 0:
                raise ValueError("invalid cost time domain")
            if target["domains_s"][domain] is not None:
                target["domains_s"][domain] += value
        target["failed_tasks"] += row["returncode"] != 0 or row.get("reason") is not None
        target["tasks"] += 1
    rows = list(grouped.values())
    complete = ledger_rows is not None and not unfinished and not missing_jobs and all(not row["unknown_attempts"] and
        row["conservative_resource_s"] is not None for row in rows)
    recorded_calls = sum(row["process_runs"] for row in rows)
    totals = dict(actual_process_runs=recorded_calls if complete else None,
                  charged_process_upper=recorded_calls if not unfinished and not missing_jobs else None,
                  recorded_ledger_charged_calls=recorded_calls,
                  missing_job_raw_starts=sum(row["recorded_process_starts"] for row in missing_jobs))
    return dict(rows=rows, unfinished_attempts=unfinished, missing_jobs=missing_jobs, complete=complete, totals=totals)


def component_costs(batches, samples):
    """Target/compile subcosts describe the full driver bill; they are not added to it."""
    grouped = {}
    for row in samples:
        component = "internal_recheck" if row["role"] == "search" and row["phase"] == "recheck" else row["role"]
        target = grouped.setdefault((row["stage"], component), dict(stage=row["stage"], component=component,
            process_runs=0, valid_runs=0, failed_runs=0, kernel_recorded_s=0.0,
            process_recorded_s=0.0, process_raw_recorded_s=0.0,
            unknown_kernel_runs=0, unknown_process_runs=0, unknown_raw_process_runs=0))
        target["process_runs"] += row["spawned"]
        target["valid_runs"] += row["valid"]
        target["failed_runs"] += not row["valid"]
        for field, total, missing in (("kernel_s", "kernel_recorded_s", "unknown_kernel_runs"),
                                      ("process_wall_s", "process_recorded_s", "unknown_process_runs"),
                                      ("process_raw_s", "process_raw_recorded_s", "unknown_raw_process_runs")):
            if finite_positive(row.get(field)):
                target[total] += row[field]
            else:
                target[missing] += 1
    builds = []
    for batch in batches:
        for task in batch["tasks"]:
            rows = [row for row in task["records"] if row["type"] == "build"]
            if not rows:
                continue
            builds.append(dict(stage=batch["manifest"]["stage"], task=task["job"]["id"], role=task["job"]["role"],
                actual_compile_processes=sum(row["type"] == "build_start" for row in task["records"]),
                cached_build_checks=sum(row["cached"] for row in rows),
                compile_recorded_s=sum(row["compile_wall_s"] for row in rows),
                incomplete_builds=task["summary"].get("incomplete_builds") if task["summary"] else None))
    return list(grouped.values()), builds


def clock_table(directory, protocol):
    """Recompute completed diagnostic clocks; no timer is presumed absolutely accurate."""
    directory = Path(directory)
    identity = load_json(directory / "identity.json")
    if identity["source_sha256"] != protocol["target"]["sha256"] or \
            identity["compiler"] != protocol["target"]["compiler_identity"]:
        raise ValueError("clock diagnostic source/compiler differs from the frozen target")
    rows = []
    for path in sorted(directory.glob("*.stdout.txt")):
        texts = path.read_text().splitlines()
        records = [json.loads(line) for line in texts if line.startswith("{")]
        intervals = [row for row in records if "start_ns" in row]
        if not intervals:
            continue
        if len(intervals) != 1:
            raise ValueError("one completed clock task must contain exactly one interval")
        record = intervals[0]
        if record["clock_order"] != ["MONOTONIC", "RAW", "REALTIME", "PROCESS_CPU"] or \
                any(type(value) is not int for value in [*record["start_ns"], *record["end_ns"]]):
            raise ValueError("unknown clock reading order or nanosecond boundaries")
        spans = [(end - start) / 1e9 for start, end in zip(record["start_ns"], record["end_ns"])]
        if len(spans) != 4 or len(record["elapsed_s"]) != 4 or any(not finite_positive(value) for value in spans) or \
                any(not math.isclose(value, printed, rel_tol=0, abs_tol=5e-10)
                    for value, printed in zip(spans, record["elapsed_s"])):
            raise ValueError("clock diagnostic elapsed fields differ from raw nanoseconds")
        cpu = spans[3]
        row = dict(task=path.stem, role="clock_probe" if "mode" in record else "clock_matrix_diagnostic",
            raw_sha256=sha256(path), mode=record.get("mode", "matrix_kernel"),
            iterations=record.get("iterations"), requested_idle_seconds=record.get("requested_idle_seconds"),
            start_ns=record["start_ns"], end_ns=record["end_ns"],
            monotonic_s=spans[0], raw_s=spans[1], realtime_s=spans[2], process_cpu_s=cpu,
            raw_over_monotonic=spans[1] / spans[0], realtime_over_monotonic=spans[2] / spans[0],
            cpu_over_raw=cpu / spans[1], absolute_clock_accuracy_verified=False)
        query = next((value for value in records if value.get("adjtimex_readonly")), None)
        if query:
            unit = "ns" if query["status"] & 0x2000 else "us"
            if query["offset_unit"] != unit:
                raise ValueError("adjtimex offset unit differs from its STA_NANO flag")
            row["adjtimex"] = query
        if record.get("mode") == "overhead":
            row["mean_four_clock_tuple_ns_including_loop"] = spans[0] * 1e9 / record["iterations"]
        if "mode" not in record:
            printed = ex.at.TargetProgram.parse(path.read_text())
            float32 = struct.unpack("f", struct.pack("f", spans[0]))[0]
            if printed != float(f"{float32:.6f}"):
                raise ValueError("matrix float tdiff/six-decimal output differs from its MONOTONIC boundaries")
            row.update(kernel_output_s=printed, output_minus_boundary_s=printed - spans[0],
                       cpu_interval="kernel only; separate from whole-target CHILDREN CPU time")
        rows.append(row)
    return dict(identity_sha256=sha256(directory / "identity.json"), identity=identity, intervals=rows,
                populations_or_absolute_accuracy_inferred=False)


def write_csv(path, rows):
    if any(isinstance(value, float) and not math.isfinite(value) for row in rows for value in row.values()):
        raise ValueError("nonfinite derived scalar cannot enter a result table")
    fields = list(dict.fromkeys(name for row in rows for name in row))
    with Path(path).open("w", newline="", encoding="utf-8") as stream:
        writer = csv.DictWriter(stream, fieldnames=fields)
        writer.writeheader()
        writer.writerows({name: json.dumps(value, ensure_ascii=False, allow_nan=False) if isinstance(value, (list, dict))
                         else value for name, value in row.items()} for row in rows)


def safe_destination(destination, batches):
    target = Path(destination).resolve()
    for batch in batches:
        raw = batch["path"].resolve()
        if target == raw or raw in target.parents:
            raise ValueError("derived output cannot overwrite or nest inside a raw batch")
    if any((parent / "plan.json").is_file() for parent in [target, *target.parents]):
        raise ValueError("derived output cannot enter another frozen raw batch")
    return target


def plot_results(directory, samples, grid, runs, curves, aa, pairs, cost_clock="CLOCK_MONOTONIC"):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True)
    created = []

    def save(fig, name):
        fig.tight_layout()
        path = directory / name
        fig.savefig(path, dpi=170)
        plt.close(fig)
        created.append(dict(path=str(path), sha256=sha256(path)))

    if grid and all(row["median_s"] is not None for row in grid):
        blocks = sorted({row["s"] for row in grid})
        fig, ax = plt.subplots(figsize=(10, 4.8))
        for offset, opt in enumerate(("O0", "O1", "O2", "O3")):
            selected = [next(row for row in grid if row["s"] == s and row["opt"] == opt) for s in blocks]
            positions = [index + (offset - 1.5) * .19 for index in range(len(blocks))]
            ax.bar(positions, [row["median_s"] for row in selected], width=.18, label=opt)
            ax.errorbar(positions, [row["median_s"] for row in selected], fmt="none", color="black", capsize=2,
                yerr=[[row["median_s"] - row["min_s"] for row in selected],
                      [row["max_s"] - row["median_s"] for row in selected]])
        ax.set_xticks(range(len(blocks)), blocks)
        ax.set(xlabel="Block size s", ylabel="Kernel time (s, logarithmic scale)", yscale="log",
               title="20 configurations: median and observed range, three runs each")
        ax.legend(ncol=4)
        save(fig, "grid_goal2.png")

    main_runs = [row for row in runs if row["stage"] == "comparison" and row["algorithm"] in ("grid", "random", "greedy")]
    if main_runs:
        seeds = sorted({row["seed"] for row in main_runs})
        fig, axes = plt.subplots(1, 2, figsize=(12, 4.7))
        for name, marker in (("grid", "s"), ("random", "o"), ("greedy", "^")):
            rows = sorted((row for row in main_runs if row["algorithm"] == name), key=lambda row: row["seed"])
            x = [seeds.index(row["seed"]) + 1 for row in rows]
            axes[0].plot(x, [row["gap_ref_pct"] for row in rows], marker=marker, label=name.capitalize())
            field = "search_driver_raw_s" if cost_clock == "CLOCK_MONOTONIC_RAW" else "search_driver_wall_s"
            axes[1].plot(x, [row[field] for row in rows], marker=marker, label=name.capitalize())
        axes[0].axhline(5, color="gray", linestyle="--", linewidth=1, label="5% target")
        axes[0].set(xlabel="Independent search block", ylabel="Returned configuration gap (%)",
                    title="Quality evaluated with one common reference table")
        axes[1].set(xlabel="Independent search block", ylabel=f"Actual search driver time (s, {cost_clock})",
                    title="Search cost, including compilation and all probes")
        for ax in axes:
            ax.set_xticks(range(1, len(seeds) + 1))
            ax.legend()
            ax.grid(alpha=.2)
        save(fig, "algorithms_goal2.png")

    if aa:
        fig, axes = plt.subplots(1, 2, figsize=(12, 4.7))
        for ax, tier in zip(axes, ("F", "M")):
            for method in ("M0", "M1"):
                rows = [row for row in samples if row["role"] == "aa" and row["tier"] == tier and row["method"] == method]
                for label, marker in (("A", "o"), ("B", "x")):
                    selected = sorted((row for row in rows if row["label"] == label), key=lambda row: row["pair"])
                    ax.plot([row["pair"] for row in selected], [row["kernel_s"] for row in selected],
                            marker=marker, label=f"{method}-{label}")
            config = next(row for row in samples if row["role"] == "aa" and row["tier"] == tier)
            ax.set(title=f"Same binary: s{config['s']}/{config['opt']}", xlabel="Predefined A/A pair", ylabel="Kernel time (s)")
            ax.set_xticks([1, 2, 3])
            ax.legend(ncol=2)
            ax.grid(alpha=.2)
        save(fig, "aa_goal2.png")

    if pairs:
        fig, axes = plt.subplots(1, 2, figsize=(12, 4.7))
        x = list(range(1, len(pairs) + 1))
        axes[0].bar(x, [row["gain_ref_pp"] for row in pairs], color="#3c78a8")
        axes[0].axhline(0, color="black", linewidth=.8)
        axes[0].set(xlabel="Paired search block", ylabel="Random gap minus S3 gap (percentage points)",
                    title="Configuration choice: common reference table")
        axes[1].bar(x, [100 * pair_cost_saving(row, {"measurement": {"cost_clock": cost_clock}}) for row in pairs], color="#527d4d")
        axes[1].axhline(10, color="gray", linestyle="--", linewidth=1)
        axes[1].axhline(0, color="black", linewidth=.8)
        axes[1].set(xlabel="Paired search block", ylabel=f"Actual search time saving (%, {cost_clock})",
                    title="One factor: six explorations and two candidate rechecks")
        for ax in axes:
            ax.set_xticks(x)
            ax.grid(axis="y", alpha=.2)
        save(fig, "recheck_goal2.png")

    if curves:
        fig, axes = plt.subplots(1, 2, figsize=(12, 4.7))
        colors = dict(grid="#377eb8", random="#4daf4a", greedy="#e41a1c", recheck="#984ea3")
        for name, color in colors.items():
            selected = [row for row in curves if row["stage"] == "comparison" and row["algorithm"] == name and
                        row.get("state", "complete") == "complete" and row["best_so_far_s"] is not None]
            for index, seed in enumerate(sorted({row["seed"] for row in selected})):
                rows = [row for row in selected if row["seed"] == seed]
                for ax, key in ((axes[0], "actual_calls"), (axes[1], "tuning_elapsed_s")):
                    ax.plot([row[key] for row in rows], [row["best_so_far_s"] for row in rows], color=color,
                            alpha=.5, marker=".", linestyle="--" if name == "recheck" else "-",
                            label="S3 updated estimate" if name == "recheck" and index == 0 else
                                  name.capitalize() if index == 0 else None)
                    rechecks = [row for row in rows if row["phase"] == "recheck"]
                    if rechecks:
                        ax.scatter([row[key] for row in rechecks], [row["best_so_far_s"] for row in rechecks],
                                   color=color, marker="^", s=22,
                                   label="S3 successful-finalist phase" if index == 0 else None)
        axes[0].set(xlabel="Actual target calls used", ylabel="Online best estimate (s)", yscale="log")
        axes[1].set(xlabel="Recorded tuning elapsed time (s, CLOCK_MONOTONIC)", ylabel="Online best estimate (s)", yscale="log")
        for ax in axes:
            ax.legend()
            ax.grid(alpha=.2)
        fig.suptitle("S3 first explores, then updates eligible finalists; its estimate may rise", fontsize=10)
        save(fig, "progress_goal2.png")
    return created


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--protocol", type=Path, required=True)
    parser.add_argument("--reference", type=Path)
    parser.add_argument("--runs", action="append", type=Path, default=[])
    parser.add_argument("--diagnostic", type=Path)
    parser.add_argument("--raw-aa", type=Path)
    parser.add_argument("--clock-followup", type=Path)
    parser.add_argument("--initial-derived", type=Path)
    parser.add_argument("--initial-root", type=Path)
    parser.add_argument("--ledger", type=Path)
    parser.add_argument("--clocks", type=Path)
    parser.add_argument("--plots", action="store_true")
    parser.add_argument("--image-dir", type=Path)
    parser.add_argument("--output-dir", type=Path, required=True)
    args = parser.parse_args(argv)
    protocol = load_json(args.protocol)
    if len({bool(args.clock_followup), bool(args.initial_derived), bool(args.initial_root)}) != 1 or \
            (args.clock_followup and (args.diagnostic or not args.ledger)):
        raise ValueError("clock followup needs its fixed initial root/output and the actual ledger; old raw is not a current diagnostic batch")
    if args.raw_aa and (args.reference or args.runs or args.diagnostic or args.clock_followup or not args.ledger):
        raise ValueError("finite RAW A/A has its own batch and exact resource-ledger snapshot")
    ledger_bytes, ledger_rows, ledger_sha = record_snapshot(args.ledger) if args.ledger else (None, None, None)
    directories = ([args.reference] if args.reference else []) + args.runs + ([args.diagnostic] if args.diagnostic else []) + \
        ([args.clock_followup] if args.clock_followup else []) + ([args.raw_aa] if args.raw_aa else [])
    if len({path.resolve() for path in directories}) != len(directories):
        raise ValueError("duplicate batches cannot be counted as new evidence")
    batches = [read_batch(path, args.protocol, args.reference) for path in directories]
    clock_health = formal_clock_health(batches, ledger_rows, protocol, ledger_bytes) if args.reference or args.runs or args.raw_aa else None
    if clock_health is not None:
        for batch in batches:
            for task in batch["tasks"]:
                journal = str((batch["path"] / (task["job"]["id"] + ".jsonl")).resolve().relative_to(ex.P1.resolve()))
                state = clock_health["states"].get(journal)
                if state in ("clock_conflict", "clock_unverified"):
                    task["state"] = state
    raw_inputs = batches + ([dict(path=args.clocks)] if args.clocks else []) + \
        ([dict(path=args.initial_derived)] if args.initial_derived else [])
    output = safe_destination(args.output_dir, raw_inputs)
    output.mkdir(parents=True, exist_ok=True)
    samples = samples_from_batches(batches)
    summary = dict(schema=2, protocol_sha256=sha256(args.protocol), analysis_sha256=sha256(__file__),
        batch_manifest_sha256={batch["path"].name: sha256(batch["path"] / "plan.json") for batch in batches},
        resource_ledger_sha256=ledger_sha,
        clock_identity_sha256=sha256(args.clocks / "identity.json") if args.clocks else None)
    summary["tasks"] = [dict(stage=batch["manifest"]["stage"], id=task["job"]["id"], role=task["job"]["role"],
        state=task["state"], actual_process_starts=sum(row["type"] == "measurement_start" for row in task["records"]),
        valid_measurements=sum(row["task"] == task["job"]["id"] and row["stage"] == batch["manifest"]["stage"] and row["valid"]
                               for row in samples),
        interrupted_measurements=sum(row["type"] == "measurement" and row["status"] == "interrupted" for row in task["records"]))
        for batch in batches for task in batch["tasks"]]
    write_csv(output / "measurements.csv", samples)
    costs = cost_table(batches, ledger_rows)
    write_csv(output / "batch_costs.csv", costs["rows"])
    summary["costs"] = costs
    summary["measurement_clock_healthy"] = clock_health["healthy"] if clock_health is not None else None
    if clock_health is not None:
        summary["measurement_clock_health"] = clock_health
    health = protocol["measurement"].get("clock_health", {})
    if health.get("clock_history"):
        summary["clock_history"] = health["clock_history"]
    numeric = health.get("numeric_baseline_identity") or {"path": health.get("numeric_binding_path")}
    if numeric.get("path") and (ex.P1 / numeric["path"]).is_file():
        summary["numeric_clock_baseline"] = dict(path=numeric["path"], sha256=sha256(ex.P1 / numeric["path"]))
    if args.clocks:
        summary["clocks"] = clock_table(args.clocks, protocol)
        write_csv(output / "clock_summary.csv", summary["clocks"]["intervals"])
    process_costs, build_costs = component_costs(batches, samples)
    write_csv(output / "process_costs.csv", process_costs)
    write_csv(output / "build_costs.csv", build_costs)
    aa, grid, runs, curves, pairs = [], [], [], [], []
    if args.diagnostic:
        aa = aa_table(samples, require_complete=False)
        summary["aa"], summary["arrangement"] = aa, choose_arrangement(aa, samples)
        write_csv(output / "aa_summary.csv", aa)
    if args.raw_aa:
        summary["raw_aa"] = raw_aa_result(samples, clock_health, costs, protocol)
        write_csv(output / "raw_aa_summary.csv", summary["raw_aa"]["aa"])
        write_csv(output / "raw_aa_rank.csv", summary["raw_aa"]["rank_comparisons"])
    if args.clock_followup:
        initial = initial_diagnostic(args.initial_root, args.initial_derived)
        followup = next(batch for batch in batches if batch["path"] == args.clock_followup.resolve())
        joined = joint_diagnostic(followup, protocol, ledger_rows, ledger_bytes, initial)
        effective = joined.pop("effective_samples")
        summary["clock_followup"] = joined
        write_csv(output / "aa_initial_partial.csv", joined["partial_aa"])
        write_csv(output / "aa_with_replacements.csv", joined["filled_aa"])
        write_csv(output / "aa_new_followup.csv", joined["new_aa"])
        write_csv(output / "clock_complete_intervals.csv", joined["clocks"]["intervals"])
        write_csv(output / "clock_prefix_timeline.csv", joined["clocks"]["timeline"])
        write_csv(output / "aa_effective_measurements.csv", effective)
    if args.reference:
        grid, complete = reference_table(samples, protocol)
        summary["reference_complete"] = complete
        write_csv(output / "grid_summary.csv", grid)
        panels = panel_table(samples, batches)
        write_csv(output / "panel_summary.csv", panels)
        runs, curves = search_tables(batches, grid, panels, protocol)
        write_csv(output / "search_summary.csv", runs)
        write_csv(output / "online_curves.csv", curves)
        stage_pairs = {}
        for stage in ("comparison", "confirmation"):
            stage_pairs[stage] = paired_rows(runs, grid, panels, protocol, stage) if complete else []
            write_csv(output / (stage + "_paired.csv"), stage_pairs[stage])
            if stage == "comparison":
                pairs = stage_pairs[stage]
        decisions = search_stage_decisions(batches, stage_pairs, protocol, complete,
            costs["complete"] and args.ledger is not None, summary["measurement_clock_healthy"])
        summary["decisions"] = decisions
        summary["retention"] = final_retention(decisions["comparison"], decisions["confirmation"])
        summary["baseline_confirmation"] = baseline_confirmation(runs, protocol["holdout"]["seeds"])
    if args.plots:
        image_dir = safe_destination(args.image_dir or output / "images", raw_inputs)
        summary["images"] = plot_results(image_dir, samples, grid, runs, curves, aa, pairs,
            protocol["measurement"].get("cost_clock", "CLOCK_MONOTONIC"))
    (output / "summary.json").write_text(json.dumps(summary, ensure_ascii=False, indent=2, allow_nan=False) + "\n")
    print(json.dumps(dict(output=str(output), **costs["totals"], costs_complete=costs["complete"]), ensure_ascii=False))
    return 0


